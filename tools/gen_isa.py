#!/usr/bin/env python3
"""Writes src/isa_ops.gen.h from src/isa.json (the ISA, once).

`python3 tools/gen_isa.py` regenerates it; `--check` fails when it is stale
(host/Makefile's `check-isa`, run in CI). The header is committed, so the
Zephyr build needs no Python.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SPEC = ROOT / "src" / "isa.json"
OUT = ROOT / "src" / "isa_ops.gen.h"


def render() -> str:
    spec = json.loads(SPEC.read_text())
    ops = spec["opcodes"]
    if ops[0]["name"] != "NOP":
        raise SystemExit("isa.json: NOP must come first (OP_NOP = 0)")
    lines = [
        "// GENERATED by tools/gen_isa.py from src/isa.json. Do not edit.",
        "#pragma once",
        "",
        f"#define TEXTOCHIP_ISA_CONTRACT {spec['contract']}",
        "",
        "// X(name): one entry per opcode, in isa.json's order.",
        "#define TEXTOCHIP_OPCODES(X) \\",
    ]
    for op in ops:
        lines.append(f"  X({op['name']}) /* {op['operands'] or '-'}: {op['doc']} */ \\")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    text = render()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            raise SystemExit("src/isa_ops.gen.h is stale: run python3 tools/gen_isa.py")
        return
    OUT.write_text(text)


if __name__ == "__main__":
    main()
